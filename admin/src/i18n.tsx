export const dictionaries = { 'zh-CN': zhCN, en, 'zh-TW': zhTW, ja, ko, th } as const
export type Locale = keyof typeof dictionaries

export const LOCALES: Array<{ code: Locale; nativeName: string }> = [
  { code: 'zh-CN', nativeName: '简体中文' },
  { code: 'zh-TW', nativeName: '繁體中文' },
  { code: 'en', nativeName: 'English' },
  { code: 'ja', nativeName: '日本語' },
  { code: 'ko', nativeName: '한국어' },
  { code: 'th', nativeName: 'ไทย' }
]

const STORAGE_KEY = 'omni_admin_locale'

export function isLocale(v: string): v is Locale {
  return v in dictionaries
}

/** 已保存的选择 > 系统语言 > 中文 */
export function initialLocale(): Locale {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved && isLocale(saved)) return saved
  const lang = navigator.language.toLowerCase()
  if (lang.startsWith('zh')) return /-(tw|hk|mo)|hant/.test(lang) ? 'zh-TW' : 'zh-CN'
  if (lang.startsWith('ja')) return 'ja'
  if (lang.startsWith('ko')) return 'ko'
  if (lang.startsWith('th')) return 'th'
  return 'en'
}

export function persistLocale(locale: Locale): void {
  localStorage.setItem(STORAGE_KEY, locale)
}

interface I18n {
  locale: Locale
  setLocale: (l: Locale) => void
  /** vars 用于 {name} 占位符替换 */
  t: (key: MessageKey, vars?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18n>({
  locale: 'zh-CN',
  setLocale: () => {},
  t: (k) => zhCN[k]
})

export function I18nProvider({ children }: { children: ReactNode }): React.JSX.Element {
  const [locale, setLocaleState] = useState<Locale>(initialLocale)

  const setLocale = (l: Locale): void => {
    setLocaleState(l)
    persistLocale(l)
  }

  const dict = dictionaries[locale] as Partial<Record<MessageKey, string>>
  const t = (key: MessageKey, vars?: Record<string, string | number>): string => {
    let text = dict[key] ?? zhCN[key]
    if (vars) {
      for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v))
    }
    return text
  }

  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>
}

export function useI18n(): I18n {
  return useContext(I18nContext)
}
